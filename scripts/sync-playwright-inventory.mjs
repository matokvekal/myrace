import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const testDocumentPath = new URL("../TEST.md", import.meta.url);
const startMarker = "<!-- PLAYWRIGHT-INVENTORY:START -->";
const endMarker = "<!-- PLAYWRIGHT-INVENTORY:END -->";

const output = execFileSync(
  process.execPath,
  ["node_modules/@playwright/test/cli.js", "test", "--list"],
  {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"]
  }
);

const tests = output
  .split(/\r?\n/)
  .map((line) => line.match(/^\s{2}[^›]+›\s+(.+?):\d+:\d+\s+›\s+(.+)$/))
  .filter(Boolean)
  .map((match) => ({ file: match[1], title: match[2] }));

if (tests.length === 0) {
  throw new Error(
    "Playwright did not report any tests; TEST.md was not changed."
  );
}

const rows = tests
  .map(
    ({ file, title }, index) =>
      `| ${index + 1} | ${file} | ${title.replaceAll("|", "\\|")} | Active |`
  )
  .join("\n");
const generatedInventory = `${startMarker}
## Generated Playwright Inventory

Generated by \`npm run test:sync\` from \`npx playwright test --list\`.
It is refreshed before every \`npm test\` run.

**Active automated cases: ${tests.length}**

| # | Spec | Playwright test | Status |
| --- | --- | --- | --- |
${rows}
${endMarker}`;

const document = readFileSync(testDocumentPath, "utf8");
const inventoryPattern = new RegExp(`${startMarker}[\\s\\S]*?${endMarker}`);
if (!inventoryPattern.test(document)) {
  throw new Error("TEST.md is missing the Playwright inventory markers.");
}

writeFileSync(
  testDocumentPath,
  document.replace(inventoryPattern, generatedInventory)
);
console.log(`Synced ${tests.length} Playwright tests into TEST.md.`);
